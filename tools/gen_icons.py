#!/usr/bin/env python3
"""Generates weather condition vector drawables (colour + Material-You themed variants).

Run from repo root:  python3 tools/gen_icons.py
"""
import math, os

RES = "app/src/main/res/drawable"
KT = "app/src/main/java/app/nimbus/weather/data/ThemedIcons.kt"

COLOR = dict(
    sun="#FFB300", halo="#FFCA28", moon="#F7D774",
    cloud="#E3E8EF", shade="#AAB6C7",
    dcloud="#B4BECB", dshade="#7D8A9C",
    rain="#3D8BFD", snow="#7DB4FF", bolt="#FFC107", fog="#A3AFC0", wind="#8DB3F2",
    hail="#FFFFFF",
)
THEMED = dict(
    sun="@color/nim_auto_primary", halo="@color/nim_auto_primary", moon="@color/nim_auto_primary",
    cloud="@color/nim_auto_icon_cloud", shade="@color/nim_auto_icon_shade",
    dcloud="@color/nim_auto_icon_shade", dshade="@color/nim_auto_icon_dark",
    rain="@color/nim_auto_tertiary", snow="@color/nim_auto_tertiary", bolt="@color/nim_auto_primary",
    fog="@color/nim_auto_icon_shade", wind="@color/nim_auto_tertiary", hail="@color/nim_auto_icon_cloud",
)

def f(x): return ("%.2f" % x).rstrip("0").rstrip(".")

def circle(cx, cy, r):
    return f"M{f(cx-r)},{f(cy)}a{f(r)},{f(r)} 0 1,1 {f(2*r)},0a{f(r)},{f(r)} 0 1,1 {f(-2*r)},0Z"

def poly(pts):
    return "M" + "L".join(f"{f(x)},{f(y)}" for x, y in pts) + "Z"

def cloud_d(shrink=0.0, lift=0.0):
    s, l = shrink, lift
    return (circle(16, 30 - l, 7.5 - s) + circle(25, 24 - l, 10.5 - s) + circle(34, 29.5 - l, 8 - s)
            + poly([(16, 30 - l), (34, 30 - l), (34, 37.5 - l - s), (16, 37.5 - l - s)]))

def crescent(cx, cy, r, ox, oy, r2, n=72):
    """Sampled crescent: arc of circle 1 outside circle 2, then arc of circle 2 inside circle 1."""
    out = []
    for k in range(n * 4):
        a = 2 * math.pi * k / (n * 4)
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        if (x - ox) ** 2 + (y - oy) ** 2 >= r2 * r2:
            out.append((a, x, y))
    # rotate list so it's contiguous
    angs = [a for a, _, _ in out]
    gaps = [(angs[(i + 1) % len(angs)] - angs[i]) % (2 * math.pi) for i in range(len(angs))]
    start = (gaps.index(max(gaps)) + 1) % len(out)
    outer = out[start:] + out[:start]
    outer = outer[::4] + [outer[-1]]
    p_end = outer[-1]; p_start = outer[0]
    a1 = math.atan2(p_end[2] - oy, p_end[1] - ox)
    a0 = math.atan2(p_start[2] - oy, p_start[1] - ox)
    inner = []
    # walk circle 2 from end point back to start point through the inside of circle 1
    for direction in (1, -1):
        pts = []
        steps = 48
        span = (a0 - a1) % (2 * math.pi) if direction == 1 else -((a1 - a0) % (2 * math.pi))
        for k in range(1, steps):
            a = a1 + span * k / steps
            pts.append((ox + r2 * math.cos(a), oy + r2 * math.sin(a)))
        if all((x - cx) ** 2 + (y - cy) ** 2 <= r * r + 0.01 for x, y in pts):
            inner = pts
            break
    return poly([(x, y) for _, x, y in outer] + inner)

class Icon:
    def __init__(self): self.items = []
    def fill(self, d, c, alpha=None): self.items.append(("fill", d, c, alpha)); return self
    def stroke(self, d, c, w=2.6): self.items.append(("stroke", d, c, w)); return self
    def group(self, s, tx, ty, build):
        self.items.append(("g+", s, tx, ty)); build(self); self.items.append(("g-",)); return self

    def xml(self, pal):
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               '<!-- Generated by tools/gen_icons.py — do not edit by hand. -->',
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
               '    android:width="48dp" android:height="48dp"',
               '    android:viewportWidth="48" android:viewportHeight="48">']
        ind = "    "
        for it in self.items:
            if it[0] == "g+":
                out.append(f'{ind}<group android:scaleX="{f(it[1])}" android:scaleY="{f(it[1])}" '
                           f'android:translateX="{f(it[2])}" android:translateY="{f(it[3])}">')
                ind += "    "
            elif it[0] == "g-":
                ind = ind[:-4]; out.append(f"{ind}</group>")
            elif it[0] == "fill":
                a = f' android:fillAlpha="{it[3]}"' if it[3] is not None else ""
                out.append(f'{ind}<path android:fillColor="{pal[it[2]]}"{a} android:pathData="{it[1]}"/>')
            else:
                out.append(f'{ind}<path android:strokeColor="{pal[it[2]]}" android:strokeWidth="{f(it[3])}" '
                           f'android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="{it[1]}"/>')
        out.append("</vector>")
        return "\n".join(out) + "\n"

def cloud(ic, dark=False):
    ic.fill(cloud_d(), "dshade" if dark else "shade")
    ic.fill(cloud_d(0.7, 1.6), "dcloud" if dark else "cloud")

def sun(ic, cx=24, cy=24, r=9):
    ic.fill(circle(cx, cy, r + 2.6), "halo", "0.35")
    ic.fill(circle(cx, cy, r), "sun")

def moon(ic, cx=24, cy=24, r=10):
    ic.fill(crescent(cx, cy, r, cx + r * 0.55, cy - r * 0.55, r * 0.82), "moon")

def drops(ic, xs, y0, length, color="rain", w=2.6):
    for x in xs:
        ic.stroke(f"M{f(x)},{f(y0)}l{f(-length*0.35)},{f(length)}", color, w)

def flake(ic, x, y, r=2.6, color="snow"):
    d = ""
    for k in range(3):
        a = math.pi / 3 * k + math.pi / 2
        dx, dy = r * math.cos(a), r * math.sin(a)
        d += f"M{f(x-dx)},{f(y-dy)}L{f(x+dx)},{f(y+dy)}"
    ic.stroke(d, color, 1.6)

def upper_cloud(ic, dark=False):
    ic.group(1.0, 0, -6, lambda g: cloud(g, dark))

icons = {}

def mk(name, build):
    ic = Icon(); build(ic); icons[name] = ic

mk("clear_day", lambda ic: sun(ic, 24, 24, 11))
mk("clear_night", lambda ic: moon(ic, 24, 24, 13))
mk("mostly_clear_day", lambda ic: (sun(ic, 21, 20, 10.5), ic.group(0.55, 21, 19.5, cloud)))
mk("mostly_clear_night", lambda ic: (moon(ic, 21, 21, 12), ic.group(0.55, 21, 19.5, cloud)))
mk("partly_cloudy_day", lambda ic: (sun(ic, 18, 17, 8.5), ic.group(0.9, 4.5, 5.5, cloud)))
mk("partly_cloudy_night", lambda ic: (moon(ic, 18, 17, 9.5), ic.group(0.9, 4.5, 5.5, cloud)))
mk("mostly_cloudy_day", lambda ic: (sun(ic, 32, 15, 6.5), ic.group(1.05, -2.5, 0.5, cloud)))
mk("mostly_cloudy_night", lambda ic: (moon(ic, 32, 15, 7.5), ic.group(1.05, -2.5, 0.5, cloud)))
mk("cloudy", lambda ic: (ic.group(0.62, 15, 3, lambda g: cloud(g, True)), ic.group(1.0, -1, 2.5, cloud)))
mk("fog", lambda ic: (upper_cloud(ic), ic.stroke("M10,37H38M14,42.5H34", "fog", 2.6)))
mk("drizzle", lambda ic: (upper_cloud(ic), drops(ic, [20, 29], 36, 5)))
mk("rain", lambda ic: (upper_cloud(ic), drops(ic, [17, 25, 33], 35.5, 7)))
mk("heavy_rain", lambda ic: (upper_cloud(ic, True), drops(ic, [14.5, 21.5, 28.5, 35.5], 35, 9)))
mk("snow", lambda ic: (upper_cloud(ic), flake(ic, 17, 38.5), flake(ic, 25, 42.5), flake(ic, 33, 38.5)))
mk("heavy_snow", lambda ic: (upper_cloud(ic, True), flake(ic, 14, 37.5), flake(ic, 21.5, 42.8), flake(ic, 28, 37.5), flake(ic, 35, 42.8)))
mk("sleet", lambda ic: (upper_cloud(ic), drops(ic, [19], 35.5, 7), flake(ic, 31, 40)))
mk("hail", lambda ic: (upper_cloud(ic, True),
                       [ (ic.fill(circle(x, y, 2.3), "hail"), ic.stroke(circle(x, y, 2.3), "snow", 1.2)) for x, y in [(17, 38), (25, 43), (33, 38)] ]))
mk("thunderstorm", lambda ic: (upper_cloud(ic, True),
                               ic.fill(poly([(26.5, 28), (19, 39), (24, 39), (21.5, 47), (30, 35), (25, 35), (28, 28)]), "bolt"),
                               drops(ic, [14, 36], 35.5, 6)))
mk("windy", lambda ic: (ic.stroke("M6,19H27a5,5 0 1,0 -5,-5", "wind", 3),
                        ic.stroke("M6,27H36a5,5 0 1,1 -5,5", "wind", 3),
                        ic.stroke("M10,35H22", "fog", 3)))

os.makedirs(RES, exist_ok=True)
for name, ic in icons.items():
    open(f"{RES}/ic_w_{name}.xml", "w").write(ic.xml(COLOR))
    open(f"{RES}/ic_w_{name}_themed.xml", "w").write(ic.xml(THEMED))

with open(KT, "w") as k:
    k.write("// Generated by tools/gen_icons.py — do not edit by hand.\npackage app.nimbus.weather.data\n\n"
            "import app.nimbus.weather.R\n\nobject ThemedIcons {\n    val map: Map<Int, Int> = mapOf(\n")
    for name in icons:
        k.write(f"        R.drawable.ic_w_{name} to R.drawable.ic_w_{name}_themed,\n")
    k.write("    )\n}\n")
print(f"generated {len(icons)} icons x2")
