#!/usr/bin/env python3
"""Generates Material You colour resources for the widget.

Widgets can't apply alpha to a *dynamic* colour at runtime without freezing it, so we
pre-generate colour-state-lists (resource + alpha) for every background tone/theme/opacity.
Resource-backed colours keep following wallpaper and dark-mode changes automatically.
"""
import os
R = "app/src/main/res"
ROLES_TONAL = {  # API 31-33 approximations from the system tonal palettes
    "surface_container":       ("system_neutral1_50",  "system_neutral1_900"),
    "primary_container":       ("system_accent1_100",  "system_accent1_700"),
    "on_primary_container":    ("system_accent1_900",  "system_accent1_100"),
    "secondary_container":     ("system_accent2_100",  "system_accent2_700"),
    "on_secondary_container":  ("system_accent2_900",  "system_accent2_100"),
    "on_surface":              ("system_neutral1_900", "system_neutral1_100"),
    "on_surface_variant":      ("system_neutral2_700", "system_neutral2_200"),
    "primary":                 ("system_accent1_600",  "system_accent1_200"),
    "tertiary":                ("system_accent3_600",  "system_accent3_200"),
    "outline_variant":         ("system_neutral2_200", "system_neutral2_700"),
    "icon_cloud":              ("system_neutral2_100", "system_neutral2_100"),
    "icon_shade":              ("system_neutral2_400", "system_neutral2_300"),
    "icon_dark":               ("system_neutral2_600", "system_neutral2_500"),
}
EXACT_34 = ["surface_container", "primary_container", "on_primary_container", "secondary_container",
            "on_secondary_container", "on_surface", "on_surface_variant", "primary", "tertiary", "outline_variant"]

def write(path, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_colors.py -->\n' + body)

def res(items):
    return "<resources>\n" + "".join(f'    <color name="{n}">{v}</color>\n' for n, v in items) + "</resources>\n"

# raw light/dark + auto (day/night) aliases
write(f"{R}/values-v31/nim_colors.xml", res(
    [(f"nim_light_{k}", f"@android:color/{l}") for k, (l, d) in ROLES_TONAL.items()] +
    [(f"nim_dark_{k}", f"@android:color/{d}") for k, (l, d) in ROLES_TONAL.items()] +
    [(f"nim_auto_{k}", f"@color/nim_light_{k}") for k in ROLES_TONAL]))
write(f"{R}/values-night-v31/nim_colors.xml", res([(f"nim_auto_{k}", f"@color/nim_dark_{k}") for k in ROLES_TONAL]))
write(f"{R}/values-v34/nim_colors.xml", res(
    [(f"nim_light_{k}", f"@android:color/system_{k}_light") for k in EXACT_34] +
    [(f"nim_dark_{k}", f"@android:color/system_{k}_dark") for k in EXACT_34]))

TONES = [("surface", "surface_container", "on_surface", "on_surface_variant", None),
         ("primary", "primary_container", "on_primary_container", "on_primary_container", "0.78"),
         ("secondary", "secondary_container", "on_secondary_container", "on_secondary_container", "0.78")]
THEMES = ["auto", "light", "dark"]
ALPHAS = list(range(0, 101, 10))

def csl(color, alpha):
    return ('<selector xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <item android:color="{color}" android:alpha="{alpha}"/>\n</selector>\n')

for tone, bg, text, var, var_alpha in TONES:
    for th in THEMES:
        for a in ALPHAS:
            write(f"{R}/color/nimbg_{tone}_{th}_{a}.xml", csl(f"@color/nim_{th}_{bg}", "%.2f" % (a / 100)))
        write(f"{R}/color/nimtext_{tone}_{th}.xml", csl(f"@color/nim_{th}_{text}", "1.0"))
        write(f"{R}/color/nimvar_{tone}_{th}.xml", csl(f"@color/nim_{th}_{var}", var_alpha or "1.0"))

kt = ["// Generated by tools/gen_colors.py — do not edit by hand.", "package app.nimbus.weather.widget", "",
      "import app.nimbus.weather.R", "", "/** Resource-backed dynamic colours indexed [tone][theme]. */", "object DynRes {"]
def arr(name, fn):
    kt.append(f"    val {name}: Array<Array<Int>> = arrayOf(")
    for tone, *_ in TONES:
        kt.append("        arrayOf(" + ", ".join(fn(tone, th) for th in THEMES) + "),")
    kt.append("    )")
arr("text", lambda t, th: f"R.color.nimtext_{t}_{th}")
arr("textVariant", lambda t, th: f"R.color.nimvar_{t}_{th}")
kt.append("    val primary = arrayOf(" + ", ".join(f"R.color.nim_{th}_primary" for th in THEMES) + ")")
kt.append("    val track = arrayOf(" + ", ".join(f"R.color.nim_{th}_outline_variant" for th in THEMES) + ")")
kt.append("    private val bgs: Array<Int> = arrayOf(")
for tone, *_ in TONES:
    for th in THEMES:
        kt.append("        " + ", ".join(f"R.color.nimbg_{tone}_{th}_{a}" for a in ALPHAS) + ",")
kt.append("    )")
kt.append(f"    fun bg(tone: Int, theme: Int, opacity: Int): Int = bgs[(tone * {len(THEMES)} + theme) * {len(ALPHAS)} + (opacity.coerceIn(0, 100) / 10)]")
kt.append("}")
open("app/src/main/java/app/nimbus/weather/widget/DynRes.kt", "w").write("\n".join(kt) + "\n")
print("ok")
